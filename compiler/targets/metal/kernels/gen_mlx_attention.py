"""Extract MLX's steel attention kernel body for mlx_attention.metal.

MLX specializes steel_attention.h with Metal function constants, which IREE's
Metal HAL cannot set. This writes, from the MLX source:

  steel_attention_ops.h    the helper ops before the kernel, without the
                           function-constant declarations; window_masked()
                           becomes a macro over the same names
  steel_attention_body.inc the body of the `attention` kernel, unchanged

mlx_attention.metal declares the function constants as template parameters
and locals with the same names and includes the body, so the MLX code is used
as is. If MLX adds or renames a function constant this fails instead of
compiling something different.

  gen_mlx_attention.py <mlx_src> <out_dir>
"""
import re
import sys
from pathlib import Path

HEADER = "mlx/backend/metal/kernels/steel/attn/kernels/steel_attention.h"
CONSTANTS = {"align_Q", "align_K", "has_mask", "do_causal", "has_sinks", "save_lse", "window_size"}
WINDOW_MASKED = (
    "#define window_masked(r, c) ((do_causal && (r) < (c)) || (has_window && \\\n"
    "    (((r) - (c)) >= window_size || (!do_causal && ((c) - (r)) >= window_size))))\n"
)


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = (src / HEADER).read_text()

    declared = set(re.findall(r"^constant (?:bool|int) (\w+) \[\[function_constant\(\d+\)\]\];", text, re.M))
    if declared != CONSTANTS:
        sys.exit(f"{HEADER}: function constants changed: {sorted(declared ^ CONSTANTS)}")

    # The ops between window_masked() and the attention kernel.
    window = re.search(r"METAL_FUNC bool window_masked\(int r, int c\) \{.*?\n\}\n", text, re.S)
    kernel = re.search(r"// clang-format off\ntemplate <\n    typename T,\n    int BQ,", text)
    if not window or not kernel:
        sys.exit(f"{HEADER}: layout changed (window_masked or attention kernel not found)")
    ops = text[window.end():kernel.start()]

    # The attention body: from the brace after its signature to the matching one.
    sig = re.search(r"void attention\(.*?\) \{ // clang-format on\n", text, re.S)
    if not sig:
        sys.exit(f"{HEADER}: attention kernel signature not found")
    depth, i = 1, sig.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    body = text[sig.end():i - 1]

    out.mkdir(parents=True, exist_ok=True)
    note = f"// Generated by compiler/targets/metal/kernels/gen_mlx_attention.py from MLX {HEADER}.\n"
    (out / "steel_attention_ops.h").write_text(
        note + "// Copyright © 2024-26 Apple Inc. (MIT)\n#pragma once\n\n" + WINDOW_MASKED + ops)
    (out / "steel_attention_body.inc").write_text(note + body)


if __name__ == "__main__":
    main()
