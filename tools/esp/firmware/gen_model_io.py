"""Input and expected output of a model run, for the ESP32-P4 firmware.

Runs the host build of the model (esp-dl dispatches on the reference kernels,
through the executable plugin) on one synthetic input and writes the raw
bytes the firmware feeds and compares:

  <out_dir>/input.bin     model input, float32, C order
  <out_dir>/expected.bin  model output, float32, C order
  <out_dir>/io.h          shapes and the text drawn on the input

usage: gen_model_io.py <plugin> <model.host.vmfb> <rec> <out_dir>
"""

import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import compare_iree_ort  # noqa: E402
import synth  # noqa: E402

SHAPES = {"rec": (1, 3, 48, 320)}
SEED = 2026


def main():
    plugin, vmfb, kind, out_dir = sys.argv[1:5]
    if kind not in SHAPES:
        sys.exit(f"unsupported model {kind}")
    shape = SHAPES[kind]
    xs, texts = synth.rec_batch(1, shape[2], shape[3], seed=SEED)
    x = xs[0].astype(np.float32)
    assert x.shape == shape, x.shape
    y = compare_iree_ort.iree_entry(vmfb, plugin)(x).astype(np.float32)

    os.makedirs(out_dir, exist_ok=True)
    x.tofile(os.path.join(out_dir, "input.bin"))
    y.tofile(os.path.join(out_dir, "expected.bin"))
    dims = lambda s: ", ".join(map(str, s))  # noqa: E731
    with open(os.path.join(out_dir, "io.h"), "w") as f:
        f.write("// Generated by tools/esp/firmware/gen_model_io.py. Do not edit.\n"
                "#pragma once\n"
                f"#define MODEL_INPUT_RANK {len(x.shape)}\n"
                f"#define MODEL_INPUT_DIMS {{{dims(x.shape)}}}\n"
                f"#define MODEL_OUTPUT_RANK {len(y.shape)}\n"
                f"#define MODEL_OUTPUT_DIMS {{{dims(y.shape)}}}\n"
                f"#define MODEL_INPUT_TEXT {text_literal(texts[0])}\n")
    print(f"{kind}: input {x.shape}, output {y.shape}, text {texts[0]!r} -> {out_dir}")


def text_literal(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
