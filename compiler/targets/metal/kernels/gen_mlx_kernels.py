"""Extract MLX kernel bodies for the IREE wrappers in this directory.

MLX specializes its steel kernels with Metal function constants, which IREE's
Metal HAL cannot set. For each kernel below this writes, from the MLX source:

  <name>_ops.h     what the header defines before the kernel, without the
                   function-constant declarations
  <name>_body.inc  the kernel's body, unchanged

The wrapper (mlx_attention.metal, mlx_gemm_nax.metal) declares the function
constants itself, as template parameters or constexpr values under the same
names, and includes the body, so MLX's code is used as is. If MLX adds or
renames a function constant this fails instead of compiling something
different.

  gen_mlx_kernels.py <mlx_src> <out_dir>
"""
import re
import sys
from pathlib import Path

KERNELS = {
    "steel_attention": {
        "header": "mlx/backend/metal/kernels/steel/attn/kernels/steel_attention.h",
        "constants": {"align_Q", "align_K", "has_mask", "do_causal", "has_sinks", "save_lse", "window_size"},
        # window_masked() reads function constants; it becomes a macro over
        # the same names so the wrapper's values apply.
        "drop": r"constant bool has_window = window_size > 0;\n.*?METAL_FUNC bool window_masked\(int r, int c\) \{.*?\n\}\n",
        "prelude": (
            "#define window_masked(r, c) ((do_causal && (r) < (c)) || (has_window && \\\n"
            "    (((r) - (c)) >= window_size || (!do_causal && ((c) - (r)) >= window_size))))\n"
        ),
        "kernel": r"// clang-format off\ntemplate <\n    typename T,\n    int BQ,",
        "signature": r"void attention\(.*?\) \{ // clang-format on\n",
    },
    "steel_attention_nax": {
        "header": "mlx/backend/metal/kernels/steel/attn/kernels/steel_attention_nax.h",
        "constants": {"align_Q", "align_K", "has_mask", "do_causal", "has_sinks", "save_lse", "window_size"},
        # The wrapper declares has_window with the other constants.
        "drop": r"constant bool has_window = window_size > 0;\n",
        "prelude": "",
        "kernel": r"// clang-format off\ntemplate <\n    typename T,\n    int BQ,",
        "signature": r"void attention_nax\(.*?\) \{ // clang-format on\n",
    },
    "steel_gemm_fused_nax": {
        "header": "mlx/backend/metal/kernels/steel/gemm/kernels/steel_gemm_fused_nax.h",
        "constants": {"has_batch", "use_out_source", "do_axpby", "align_M", "align_N", "align_K"},
        "drop": None,
        "prelude": "",
        "kernel": r"// clang-format off\ntemplate <\n    typename T,\n    int BM,",
        "signature": r"void gemm\(.*?\) \{ // clang-format on\n",
    },
}
CONSTANT = re.compile(r"^constant (?:bool|int) (\w+) \[\[function_constant\(\d+\)\]\];\n", re.M)


def extract(src, spec):
    header = spec["header"]
    text = (src / header).read_text()
    declared = set(CONSTANT.findall(text))
    if declared != spec["constants"]:
        sys.exit(f"{header}: function constants changed: {sorted(declared ^ spec['constants'])}")

    kernel = re.search(spec["kernel"], text)
    sig = re.search(spec["signature"], text, re.S)
    if not kernel or not sig:
        sys.exit(f"{header}: layout changed (kernel template or signature not found)")

    # Everything before the kernel, minus the function constants.
    ops = CONSTANT.sub("", text[:kernel.start()])
    if spec["drop"]:
        ops, n = re.subn(spec["drop"], "", ops, flags=re.S)
        if n != 1:
            sys.exit(f"{header}: layout changed (code to replace not found)")

    # The body: from the brace after the signature to the matching one.
    depth, i = 1, sig.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return ops, text[sig.end():i - 1]


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    for name, spec in KERNELS.items():
        ops, body = extract(src, spec)
        note = f"// Generated by compiler/targets/metal/kernels/gen_mlx_kernels.py from MLX {spec['header']}.\n"
        (out / f"{name}_ops.h").write_text(
            note + "// MLX: MIT, Copyright Apple Inc.\n#pragma once\n\n" + spec["prelude"] + ops)
        (out / f"{name}_body.inc").write_text(note + body)


if __name__ == "__main__":
    main()
